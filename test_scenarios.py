def run_positive():
    print("【正向】规范话术应通过上岗认证")
    ok = True
    for pid, (pos_name, lines) in POSITIVE.items():
        p, pos = PERSONA_MAP[pid], POSITIONS[pos_name]
        msgs = [{"role": "customer", "content": p["opening"]}]
        for i, l in enumerate(lines, 1):
            msgs.append({"role": "cs", "content": l, "turn": i})
            if i < len(lines):
                msgs.append({"role": "customer", "content": "（客户追问）"})
        r = scoring.score(msgs, p, pos)
        good = r["passed"]
        ok &= good
        print(f"  {'✅' if good else '❌'} {p['name']:16s} 总分 {r['total']:5.1f}  合规 {r['dims']['规范合规']:5.1f}")
        if not good:
            print(f"       红线 {[x['rule']['name'] for x in r['red_hits']]}"
                  f"  缺失 {r['missing']}  黄线 {[y['name'] for y in r['yellows']]}")
    return ok


def run_negative():
    print("\n【反向】违规话术应命中红线并被判不通过")
    ok = True
    for pid, bad in NEGATIVE:
        p = PERSONA_MAP[pid]
        msgs = [{"role": "customer", "content": p["opening"]},
                {"role": "cs", "content": bad, "turn": 1}]
        r = scoring.score(msgs, p, POSITIONS["10086 呼入客服"])
        caught = bool(r["red_hits"]) and not r["passed"]
        ok &= caught
        names = [x["rule"]["name"] for x in r["red_hits"]]
        print(f"  {'✅' if caught else '❌'} {p['name'][:12]:14s} 总分 {r['total']:5.1f}  红线 {names or '【漏检】'}")
    return ok


if __name__ == "__main__":
    a, b = run_positive(), run_negative()
    print("\n" + ("全部通过 ✅ 评分模型判别力正常" if (a and b) else "存在失败项 ❌ 请检查规则库"))
    sys.exit(0 if (a and b) else 1)
